-- ============================================================
-- "Πρόσθεσε προϊόν" — δύο ακόμα επιλογές (20/9, ρητό αίτημα χρήστη):
--
-- 1) "Να εμφανίζεται και στα New Arrivals" — μέχρι τώρα το "New Arrivals"
--    ήταν ΑΠΟΚΛΕΙΣΤΙΚΑ αυτόματο (product_variants... όχι, εδώ: products
--    με created_at μέσα στους τελευταίους 6 μήνες, βλ.
--    hooks/useMerchCategories.js). Ο admin θέλει να μπορεί να το
--    "τσεκάρει" χειροκίνητα κι αυτός, ανεξάρτητα από πότε καταχωρήθηκε
--    πραγματικά στο σύστημα.
--
-- 2) "Θα είναι διαθέσιμο από τότε" — προγραμματισμένη διαθεσιμότητα: ο
--    admin μπορεί να καταχωρήσει το προϊόν (με τις πραγματικές του
--    ποσότητες) ΠΡΙΝ την ημερομηνία/ώρα που θέλει να "ανοίξει" η πώληση.
--    Μέχρι τότε το προϊόν φαίνεται ΚΑΝΟΝΙΚΑ στο κατάστημα (ρητό αίτημα
--    χρήστη — "να εμφανίζεται κανονικά") αλλά με ένδειξη "Διαθέσιμο από
--    ..." αντί για stock badge, και ΔΕΝ μπορεί να μπει στο καλάθι.
--
--    ΣΚΟΠΙΜΑ καμία server-side/cron λογική εδώ (ΟΧΙ δεύτερο pg_cron
--    job, ΟΧΙ boolean flag που πρέπει κάποιος/κάτι να "γυρίσει" τη
--    σωστή στιγμή) — το ήδη υπάρχον bug με το get_active_stock_holds
--    (migration 20260919091000, το κενό ~60 δευτ. ανάμεσα σε
--    expires_at και το επόμενο cron tick) έδειξε ότι stored state που
--    πρέπει να "προλάβει" ένα ρολόι είναι εύθραυστο. Αντί γι' αυτό: η
--    διαθεσιμότητα υπολογίζεται ΖΩΝΤΑΝΑ στο frontend σε κάθε render/
--    refetch (products.available_from vs Date.now(), βλ.
--    lib/stockTiers.js/isScheduledUnavailable) — το ήδη υπάρχον
--    refetchInterval:15000 στο useProducts.js κάνει το "αυτόματα, χωρίς
--    ο admin να ξανασχοληθεί" να δουλεύει μόνο του, χωρίς κανένα νέο
--    background job.
-- ============================================================

alter table public.products
  add column if not exists is_new_arrival boolean not null default false;

-- NULL = διαθέσιμο αμέσως (η σημερινή, προεπιλεγμένη συμπεριφορά για ΟΛΑ
-- τα ήδη υπάρχοντα προϊόντα — καμία αλλαγή γι' αυτά). Τιμή στο μέλλον =
-- "κλειδωμένο" μέχρι τότε.
alter table public.products
  add column if not exists available_from timestamptz;
